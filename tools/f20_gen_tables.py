"""Stage F20: writes src\\lockstep\\generated_tables.hpp (names and addresses only, no ROM bytes).

  python -I tools\\f20_gen_tables.py

Contents: the 6502 opcode table (mnemonic, addressing mode, cycles, length; from tools\\f1_6502.py, which was read from Stella's DiStella table),
the routine list of F8 (entry, size, name) with the parts of the main loop (F5), and the RAM names of F7. The lockstep tool uses them to name the
routine that last wrote a byte that differs.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import f1_6502 as asm  # noqa: E402


def main():
    mns = sorted({e[0].upper() for e in asm.TABLE if e and e[4]})
    modes = list(asm.MODES)
    out = ['// Generated by tools/f20_gen_tables.py (Stage F20). Names and addresses only; no ROM bytes. Do not edit.', '#pragma once', '#include <cstdint>', '',
           'namespace lockstep {', '', 'enum Mn : uint8_t { MN_ILL, ' + ', '.join('MN_' + m for m in mns) + ' };',
           'enum Mode : uint8_t { ' + ', '.join('MODE_' + m for m in modes) + ' };', '',
           'struct OpInfo { Mn mn; Mode mode; uint8_t cycles; uint8_t length; };', 'inline constexpr OpInfo kOps[256] = {']
    for op in range(256):
        e = asm.TABLE[op]
        if e and e[4]:
            out.append('  {MN_%s, MODE_%s, %d, %d},' % (e[0].upper(), e[1], e[2], e[3]))
        else:
            out.append('  {MN_ILL, MODE_IMPLIED, 2, 1},')
    out += ['};', '', 'struct Region { uint16_t start; uint16_t size; const char* name; };', 'inline constexpr Region kRegions[] = {']
    text = (ROOT / 'docs' / 'F8_ROUTINES.md').read_text(encoding='utf-8')
    block = text[text.index('## Routines'):text.index('## Data each routine')]
    regions = []
    for line in block.split('\n'):
        m = re.match(r'\| \$([0-9A-F]{4}) \| `(\w+)` \| [^|]* \| (\d+) \|', line)
        if m and m.group(2) != 'MAIN':
            regions.append((int(m.group(1), 16), int(m.group(3)), m.group(2)))
    # the parts of the main loop (F5 landmarks): start-up, sprite set-up, picture, bottom logic, waits, frame start, top logic
    parts = [(0xF000, 0x53, 'MAIN/start-up'), (0xF07F, 0xF0C5 - 0xF07F, 'MAIN/sprite positions'), (0xF0C5, 5, 'MAIN/vertical-blank wait'),
             (0xF0CA, 0xF4E7 - 0xF0CA, 'MAIN/picture kernel'), (0xF4E7, 0xF7D1 - 0xF4E7, 'MAIN/bottom logic'), (0xF7D1, 5, 'MAIN/overscan wait'),
             (0xF7D6, 0xF87C - 0xF7D6, 'MAIN/frame start'), (0xF87C, 0xF9AA - 0xF87C, 'MAIN/top logic')]
    for r in sorted(regions + parts):
        out.append('  {0x%04X, %d, "%s"},' % r)
    out += ['};', '', 'struct RamName { uint8_t addr; const char* name; };', 'inline constexpr RamName kRamNames[] = {']
    ram = (ROOT / 'docs' / 'F7_RAM_MAP.md').read_text(encoding='utf-8')
    for line in ram.split('\n'):
        m = re.match(r'\| \$([0-9A-F]{2}) \| `(\w+)`', line)
        if m:
            out.append('  {0x%s, "%s"},' % (m.group(1), m.group(2)))
    out += ['};', '', '}  // namespace lockstep', '']
    dest = ROOT / 'src' / 'lockstep' / 'generated_tables.hpp'
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print('wrote', dest, len(mns), 'mnemonics,', len(regions) + len(parts), 'regions')


if __name__ == '__main__':
    main()
