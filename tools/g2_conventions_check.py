"""Stages G2 and G5: measures docs\\CONVENTIONS.md on src\\game, src\\host, src\\testsupport and src\\lockstep.

python -I tools\\g2_conventions_check.py [--strict]

Reports files over 400 lines, functions over 80 lines (a definition starting in column 0, or indented by two spaces for a class member,
with its '{' on the same line or on the next; up to the closing '}' at the same indent), lines over 160 characters, the number of
ORIGINAL: tags and every tag whose 'Evidence:' path does not exist.

Approved exceptions (EXCEPTIONS, each with its reason; recorded in DECISIONS.md T-G5-2) are listed apart and do not count.
Exit 0 unless --strict and something that is not an approved exception was found.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILE_LIMIT, FUNC_LIMIT, LINE_LIMIT = 400, 80, 160

# (path as printed, function name or '*' for "every line/file", reason)
EXCEPTIONS = {
    'files': {
        'src/lockstep/generated_tables.hpp': 'generated by tools/f20_gen_tables.py (tables of names and regions)',
    },
    'functions': {
        ('src/game/picture/kernel_maze.cpp', 'mazeRows'): 'the original\'s loop over the labels L_F0F4..L_F360, written as the jumps it has; cutting at a label changes the jumps (T-G5-2)',
        ('src/game/picture/kernel_score.cpp', 'scoreLine'): 'one straight run of timed chip writes with two nested lambdas; splitting only moves lines (T-G5-2)',
        ('src/game/logic/pacman.cpp', 'joystickAndMove'): 'the original\'s state machine over the labels L_F6DD..L_F781, kept as jumps (T-G5-2)',
        ('src/host/play_window.cpp', 'playWindow'): 'one game loop with its threads, start-up and shut-down; Phase D code moved unchanged (T-G5-2)',
        ('src/host/pads.cpp', 'padCheck'): 'a test script: one long sequence of reported steps (T-G5-2)',
        ('src/host/main.cpp', 'main'): 'the one start-up sequence of the program: what to run, the window, the shut-down (T-G5-2)',
        ('src/host/headless.cpp', 'headlessRun'): 'a test mode: one sequence of set-up, run and report (T-G5-2)',
    },
    'long_lines': ('src/host/', 'src/lockstep/', 'src/testsupport/'),   # code moved unchanged from Phase D and the test tool; not worth reformatting (T-G5-2)
}
TEST_CODE = ('src/lockstep/',)   # the lockstep tool: function length is reported but not required (T-G5-2)

SIG = re.compile(r'^( {0,2})(?!(?:if|for|while|switch|else|return|catch|namespace|class|struct|enum|union)\b)[A-Za-z_][\w:<>,&\*\[\] ]*\b([A-Za-z_]\w*)\(.*\)\s*(const)?\s*(\{\s*)?$')


def sources():
    for sub in ('game', 'host', 'testsupport', 'lockstep'):
        for ext in ('*.cpp', '*.hpp'):
            yield from sorted((ROOT / 'src' / sub).rglob(ext))


def main():
    strict = '--strict' in sys.argv
    big_files, big_funcs, long_lines, tags, bad_tags = [], [], [], 0, []
    approved = []
    for f in sources():
        rel = str(f.relative_to(ROOT)).replace('\\', '/')
        lines = f.read_text(encoding='utf-8', errors='replace').splitlines()
        if len(lines) > FILE_LIMIT:
            if rel in EXCEPTIONS['files']:
                approved.append('file %s (%d lines): %s' % (rel, len(lines), EXCEPTIONS['files'][rel]))
            else:
                big_files.append((rel, len(lines)))
        start = None
        for n, line in enumerate(lines, 1):
            if len(line) > LINE_LIMIT:
                if rel.startswith(EXCEPTIONS['long_lines']):
                    approved.append('')
                else:
                    long_lines.append((rel, n))
            if start is None:
                m = SIG.match(line)
                if m and (m.group(4) or (n < len(lines) and lines[n].strip() == '{' and not lines[n].startswith(' '))):
                    start = (n, m.group(1), m.group(2))
            elif line.startswith(start[1] + '}') and not line.startswith(start[1] + '} '):
                size = n - start[0] + 1
                if size > FUNC_LIMIT:
                    key = (rel, start[2])
                    if key in EXCEPTIONS['functions']:
                        approved.append('function %s::%s (%d lines): %s' % (rel, start[2], size, EXCEPTIONS['functions'][key]))
                    elif rel.startswith(TEST_CODE):
                        approved.append('function %s::%s (%d lines): lockstep tool, test code' % (rel, start[2], size))
                    else:
                        big_funcs.append((rel, start[0], start[2], size))
                start = None
            if '// ORIGINAL:' in line:
                tags += 1
                m = re.search(r'Evidence:\s*([^\s;,)]+(?:\\[^\s;,)]+)*)', line)
                p = m.group(1).rstrip('.') if m else None
                if not p or not (ROOT / p.replace('\\', '/')).exists():
                    bad_tags.append((rel, n, p))
    print('files over %d lines: %d' % (FILE_LIMIT, len(big_files)))
    for x in big_files:
        print('  %s  %d' % x)
    print('functions over %d lines: %d' % (FUNC_LIMIT, len(big_funcs)))
    for x in big_funcs:
        print('  %s:%d  %s  %d lines' % x)
    print('lines over %d characters: %d' % (LINE_LIMIT, len(long_lines)))
    for x in long_lines[:20]:
        print('  %s:%d' % x)
    print('ORIGINAL: tags: %d, with a missing evidence path: %d' % (tags, len(bad_tags)))
    for x in bad_tags:
        print('  %s:%d  %s' % x)
    named = [a for a in approved if a]
    print('approved exceptions: %d (%d long lines in code moved unchanged: src/host, src/lockstep, src/testsupport)' % (len(named), len(approved) - len(named)))
    for a in named:
        print('  ' + a)
    found = len(big_files) + len(big_funcs) + len(long_lines) + len(bad_tags)
    print('result: %s' % ('CLEAN' if found == 0 else 'findings: %d (%s)' % (found, 'strict, failing' if strict else 'report only')))
    return 1 if strict and found else 0


if __name__ == '__main__':
    sys.exit(main())
