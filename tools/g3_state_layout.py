"""Stage G3: where each named byte of the original's memory sits in game::GameState.

python -I tools\\g3_state_layout.py

Reads the names of the 128 bytes (src\\testsupport\\ram_map.hpp, made by tools\\f20_gen_tables.py) and gives each its field in game::GameState
(src\\game\\state.hpp). Writes src\\testsupport\\state_layout_checks.hpp: one static_assert per byte, so the build fails if a field is not exactly
where the F7 map says. Must say "128 of 128".
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAM_MAP = ROOT / 'src' / 'testsupport' / 'ram_map.hpp'
OUT = ROOT / 'src' / 'testsupport' / 'state_layout_checks.hpp'

SCALARS = {
    'FRAME_COUNTER': 'frameCounter', 'TICK256': 'tick256', 'ATTRACT_SHIFT': 'attractShift', 'SELECT_REPEAT': 'selectRepeat',
    'GAME_SELECT': 'gameSelect', 'Y_OFFSET': 'yOffset', 'X_OFFSET': 'xOffset', 'CELL_INDEX': 'cellIndex', 'SPRITE_X': 'spriteX',
    'CELL_ROW': 'cellRow', 'ROW_PARITY': 'rowParity', 'RNG_STATE': 'rng', 'EVENT_TIMER': 'eventTimer', 'EAT_PAUSE': 'eatPause',
    'PLAYER_MODE': 'playerMode', 'GAME_FLAGS': 'gameFlags', 'SOUND_ACTIVE': 'soundActive', 'SOUND_TIMER': 'soundTimer',
    'UNUSED_EA': 'unusedEA', 'UNUSED_EB': 'unusedEB', 'BONUS_TIMER': 'bonusTimer', 'JOY_DIRECTION': 'joyDirection',
    'POS_CODE': 'posCode', 'COLOUR_MASK': 'colourMask',
}
PLAYER_FIELDS = {'LIVES': 'lives', 'LEVEL_SPEED': 'level', 'PILL_FLAGS': 'pillFlags', 'SCORE_COLOUR': 'scoreColour'}
SCRATCH = {
    'TEMP_D2': 'kTempD2', 'TEMP_D3': 'kTempD3', 'TEMP_D4': 'kTempD4', 'TEMP_D5': 'kTempD5', 'TEMP_D6': 'kTempD6', 'TEMP_D7': 'kTempD7',
    'SPRITE0_Y': 'kSprite0Y', 'SPRITE1_Y': 'kSprite1Y', 'TEMP_DA': 'kTempDA', 'SPRITE0_LINES': 'kSprite0Lines',
    'SPRITE1_LINES': 'kSprite1Lines', 'SPRITE0_PTR_LO': 'kSprite0PtrLo', 'SPRITE0_PTR_HI': 'kSprite0PtrHi',
    'SPRITE1_PTR_LO': 'kSprite1PtrLo', 'SPRITE1_PTR_HI': 'kSprite1PtrHi', 'TEMP_E1': 'kTempE1', 'TEMP_E2': 'kTempE2', 'TEMP_E3': 'kTempE3',
}
COLOUR = {'COLOUR_BG': 'kColourBg', 'COLOUR_MAZE': 'kColourMaze', 'COLOUR_SPRITE0': 'kColourSprite0', 'COLOUR_SPRITE1': 'kColourSprite1',
          'COLOUR_SCORE_P2': 'kColourScoreP2', 'COLOUR_SCORE_P1': 'kColourScoreP1'}


def read_names():
    names = []
    for m in re.finditer(r'inline constexpr uint8_t (\w+) = 0x([0-9A-Fa-f]+);', RAM_MAP.read_text(encoding='utf-8')):
        names.append((m.group(1), int(m.group(2), 16)))
    return names


def field(name):
    """(array or field path, index text or None) for a name; the path is relative to a GameState called `st`."""
    if name in SCALARS:
        return SCALARS[name], None
    m = re.fullmatch(r'MAZE_(P2_)?(\d\d)', name)
    if m:
        return 'player[%d].maze' % (1 if m.group(1) else 0), str(int(m.group(2)))
    m = re.fullmatch(r'(\w+?)(_P2)?', name)
    if m and m.group(1) in PLAYER_FIELDS:
        return 'player[%d].%s' % (1 if m.group(2) else 0, PLAYER_FIELDS[m.group(1)]), None
    if name == 'PACMAN_X': return 'objX', '0'
    if name == 'PACMAN_Y': return 'objY', '0'
    if name == 'PACMAN_STATE': return 'objState', '0'
    m = re.fullmatch(r'GHOST_(X|Y|STATE)(\d)', name)
    if m: return {'X': 'objX', 'Y': 'objY', 'STATE': 'objState'}[m.group(1)], str(int(m.group(2)) + 1)
    m = re.fullmatch(r'SPEED_ACC(\d)', name)
    if m: return 'speedAcc', m.group(1)
    m = re.fullmatch(r'GHOST_TIMER(\d)', name)
    if m: return 'ghostTimer', m.group(1)
    m = re.fullmatch(r'SCORE_P([12])_(LO|MID|HI)', name)
    if m: return 'score', str(2 * ['LO', 'MID', 'HI'].index(m.group(2)) + int(m.group(1)) - 1)
    if name in SCRATCH: return 'scratch', SCRATCH[name]
    if name in COLOUR: return 'colour', COLOUR[name]
    m = re.fullmatch(r'STACK_([0-9A-F]{2})', name)
    if m: return 'stack', str(int(m.group(1), 16) - 0xF6)
    raise KeyError(name)


def expression(name):
    f, i = field(name)
    return 'st.' + f + ('' if i is None else '[%s]' % i)


def offset_expr(name):
    """A constant expression for the offset of that name inside GameState."""
    f, i = field(name)
    parts = []
    m = re.fullmatch(r'player\[(\d)\]\.(\w+)', f)
    if m:
        parts.append('offsetof(GameState, player) + %s * sizeof(PlayerBlock) + offsetof(PlayerBlock, %s)' % (m.group(1), m.group(2)))
    else:
        parts.append('offsetof(GameState, %s)' % f)
    if i is not None:
        parts.append(i)
    return ' + '.join(parts)


def main():
    names = read_names()
    if len(names) != 128:
        print('expected 128 names, found', len(names))
        return 1
    lines = ['// Generated by tools/g3_state_layout.py (Stage G3). One check per byte of the original\'s memory: the field of game::GameState that holds it',
             '// sits exactly where the F7 map says. Do not edit.',
             '#pragma once', '#include <cstddef>', '', '#include "../game/state/state.hpp"', '#include "ram_map.hpp"', '',
             'namespace testsupport {', 'using namespace game;', '']
    seen = set()
    for name, addr in names:
        lines.append('static_assert(%s == ram::%s - 0x80, "%s");' % (offset_expr(name), name, name))
        seen.add(addr)
    lines += ['', '}  // namespace testsupport', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    ok = seen == set(range(0x80, 0x100))
    print('%d of 128 names placed; every address $80-$FF named once: %s' % (len(names), ok))
    print('wrote', OUT.relative_to(ROOT))
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
